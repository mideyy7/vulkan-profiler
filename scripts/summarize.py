"""Prints the headline numbers, each traced to the CSV it came from.

Usage: python3 scripts/summarize.py RESULTS_DIR > RESULTS_DIR/headline.md
"""

import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from plot_common import frame_mean_us, gpu_label, read_sweep  # noqa: E402

out = Path(sys.argv[1])
meta, _ = read_sweep(out, "sweep_naive_batch1")

print(f"# Headline results: {gpu_label(meta)}\n")
print("Generated by `scripts/summarize.py` from the CSVs in this folder.\n")

# Batching at N = 2048: ratio of median mean frame time per step over 5 runs.
print("## Batching at N = 2048 (naive kernel)\n")
print("| batch K | frame µs/step, median of 5 | fastest run | slowest run | speed-up vs K = 1 |")
print("| --- | --- | --- | --- | --- |")
medians = {}
for k in [1, 2, 4, 8, 16, 32, 64]:
    runs = sorted(frame_mean_us(out / f"report_n2048_batch{k}_run{r}.csv") for r in range(1, 6))
    medians[k] = statistics.median(runs)
    print(f"| {k} | {medians[k]:.1f} | {runs[0]:.1f} | {runs[-1]:.1f} "
          f"| {medians[1] / medians[k]:.2f}× |")
print(f"\nSource: `report_n2048_batch{{K}}_run{{1..5}}.csv`.\n")

# Fixed overhead across N, unbatched against batched.
_, b1 = read_sweep(out, "sweep_naive_batch1")
_, b32 = read_sweep(out, "sweep_naive_batch32")
print("## Overhead per step (frame − GPU span), naive kernel\n")
print("| N | batch 1: frame µs | batch 1: overhead µs | batch 32: frame µs "
      "| batch 32: overhead µs |")
print("| --- | --- | --- | --- | --- |")
for r1, r32 in zip(b1, b32):
    print(f"| {r1['n']} | {float(r1['frame_mean_ns']) / 1e3:.1f} "
          f"| {float(r1['overhead_mean_ns']) / 1e3:.1f} "
          f"| {float(r32['frame_mean_ns']) / 1e3:.1f} "
          f"| {float(r32['overhead_mean_ns']) / 1e3:.1f} |")
print("\nSource: `sweep_naive_batch1_run{1..3}.csv`, `sweep_naive_batch32_run{1..3}.csv` (median of 3 runs each).\n")

# Tiling, both batched with K = 32.
_, tiled = read_sweep(out, "sweep_tiled_batch32")
print("## Tiled against naive force kernel (batch 32)\n")
print("| N | naive force µs | tiled force µs | force speed-up | naive frame µs "
      "| tiled frame µs | frame speed-up |")
print("| --- | --- | --- | --- | --- | --- | --- |")
for rn, rt in zip(b32, tiled):
    fn, ft = float(rn["force_mean_ns"]), float(rt["force_mean_ns"])
    gn, gt = float(rn["frame_mean_ns"]), float(rt["frame_mean_ns"])
    print(f"| {rn['n']} | {fn / 1e3:.1f} | {ft / 1e3:.1f} | {fn / ft:.2f}× "
          f"| {gn / 1e3:.1f} | {gt / 1e3:.1f} | {gn / gt:.2f}× |")
print("\nSource: `sweep_naive_batch32_run{1..3}.csv`, `sweep_tiled_batch32_run{1..3}.csv` (median of 3 runs each).")
